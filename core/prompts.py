"""系统提示词与 Skill 加载"""
from core.config import BASE_DIR

SKILLS_DIR = BASE_DIR / "skills"


def load_skill(name: str) -> str:
    """从 skills/ 目录加载 skill markdown 文件内容"""
    path = SKILLS_DIR / name
    if path.is_file():
        return path.read_text(encoding="utf-8")
    return ""


